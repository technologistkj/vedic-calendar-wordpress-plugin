#!/usr/bin/env python3
"""Writes includes/vsop87-earth-l.php: the VSOP87D series for the Earth's
heliocentric longitude, cut down to the terms that matter for 1900-2600.

    python3 -m venv /tmp/v && /tmp/v/bin/pip install pymeeus
    /tmp/v/bin/python bin/gen-vsop.py

A term is kept when its amplitude, times 0.3 to the power of its series, is at
least 2e-8 radians. That keeps 207 of 1,080 terms. Measured against Swiss
Ephemeris over 1900-2600, sankranti times come out within 3.3 s, which the full
series does not improve on (3.6 s); with the earlier cut, 149 terms, they were
within 5.5 s.
"""
import os
from pymeeus import Earth

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THRESHOLD = 2.0

series = [[t for t in terms if t[0] * (0.3 ** p) >= THRESHOLD] for p, terms in enumerate(Earth.VSOP87_L)]

lines = [
    '<?php',
    '/**',
    ' * VSOP87D, Earth, heliocentric longitude (L0..L5), referred to the mean',
    ' * equinox and ecliptic of date. Amplitudes in 1e-8 radians; each row is',
    ' * array( A, B, C ) for A cos( B + C tau ), tau in Julian millennia from J2000.',
    ' *',
    ' * Generated by bin/gen-vsop.py from the full series (Bretagnon & Francou',
    ' * 1988, as published in PyMeeus). Do not edit by hand.',
    ' *',
    ' * @package AindramVedicCalendar',
    ' */',
    '',
    "defined( 'ABSPATH' ) || exit;",
    '',
    'return array(',
]
for p, terms in enumerate(series):
    lines.append(f'\t// L{p}: {len(terms)} terms.')
    lines.append('\tarray(')
    for a, b, c in terms:
        lines.append(f'\t\tarray( {a!r}, {b!r}, {c!r} ),')
    lines.append('\t),')
lines.append(');')
lines.append('')

out = os.path.join(ROOT, 'includes', 'vsop87-earth-l.php')
open(out, 'w', encoding='utf-8').write('\n'.join(lines))
print(out, sum(len(t) for t in series), 'terms')
