#!/usr/bin/env python3
"""Writes includes/delta-t.php: Delta T (TT - UT), in seconds, every two years
from 1800 to 2700, as Swiss Ephemeris gives it, and a parabola fitted to Swiss
Ephemeris on either side, so the curve is continuous at both ends.

    python3 -m venv /tmp/v && /tmp/v/bin/pip install pyswisseph
    /tmp/v/bin/python bin/gen-deltat.py

Up to the present these are the observed values; after that they are Swiss
Ephemeris's extrapolation (Stephenson, Morrison and Hohenkerk 2016, joined to
the observations). Nobody can know the Earth's rotation centuries ahead, so the
future values are a convention; matching the one every Swiss Ephemeris based
almanac uses is what keeps this plugin's dates in step with theirs. Linear
interpolation in a two-year table stays within 0.2 s of Swiss Ephemeris.
"""
import os
import swisseph as swe

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIRST, LAST, STEP = 1800, 2700, 2


def dt(year):
    # Decimal year to JD the same way the PHP does: 2000.0 = JD 2451545.0.
    return swe.deltat(2451545.0 + (year - 2000) * 365.25) * 86400


values = [round(dt(y), 2) for y in range(FIRST, LAST + 1, STEP)]


def parabola(edge, sign):
    """b, c of dT = v(edge) + b u + c u^2, u years beyond the edge, through
    Swiss Ephemeris 100 and 300 years out."""
    v0, v1, v3 = dt(edge), dt(edge + sign * 100), dt(edge + sign * 300)
    c = ((v3 - v0) / 300 - (v1 - v0) / 100) / 200
    return round((v1 - v0) / 100 - 100 * c, 6), round(c, 8)


before, after = parabola(FIRST, -1), parabola(LAST, +1)

lines = [
    '<?php',
    '/**',
    ' * Delta T (TT - UT) in seconds, %d to %d every %d years, from Swiss' % (FIRST, LAST, STEP),
    ' * Ephemeris %s; a parabola on either side. Generated by bin/gen-deltat.py. Do not' % swe.version,
    ' * edit by hand.',
    ' *',
    ' * @package AindramVedicCalendar',
    ' */',
    '',
    "defined( 'ABSPATH' ) || exit;",
    '',
    'return array(',
    "\t'first'  => %d," % FIRST,
    "\t'step'   => %d," % STEP,
    "\t'before' => array( %r, %r ),  // b, c for u = %d - year" % (before + (FIRST,)),
    "\t'after'  => array( %r, %r ),  // b, c for u = year - %d" % (after + (LAST,)),
    "\t'values' => array(",
]
for i in range(0, len(values), 10):
    lines.append('\t\t' + ', '.join('%.2f' % v for v in values[i:i + 10]) + ',')
lines += ['\t),', ');', '']
out = os.path.join(ROOT, 'includes', 'delta-t.php')
open(out, 'w', encoding='utf-8').write('\n'.join(lines))
print(out, len(values), 'values; before', before, 'after', after)
